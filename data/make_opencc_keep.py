"""Regenerate data/opencc_keep.txt.

Whisper already writes Traditional Chinese, but OpenCC treats its input as
Simplified, so it "converts" characters that are already valid Traditional:
「就是只是」 became 「就是隻是」, 「干擾」 became 「幹擾」. The fix is to keep every
character that OpenCC's own Simplified-to-Traditional table lists among its
own candidates (只 -> 只 隻): such a character is valid in both scripts.

This script reads that table (and the phrase table, for examples) from a pinned
OpenCC commit and writes one character per line with a note on what OpenCC
would turn it into. transcribe.py only reads the first character of each line.

Usage: .venv/bin/python data/make_opencc_keep.py
"""
import urllib.request
from pathlib import Path

import opencc

COMMIT = "178f05dbc5dbcedd09d4ab39d501094f4d9d8820"  # OpenCC master, 2026-07-17
BASE = f"https://raw.githubusercontent.com/BYVoid/OpenCC/{COMMIT}/data/dictionary"
OUT = Path(__file__).resolve().parent / "opencc_keep.txt"


def fetch(name):
    with urllib.request.urlopen(f"{BASE}/{name}") as r:
        return r.read().decode("utf-8")


def table(text):
    for line in text.splitlines():
        key, _, values = line.partition("\t")
        if key:
            yield key, values.split(" ")


def main():
    keep = [k for k, vs in table(fetch("STCharacters.txt")) if k in vs]
    cc = opencc.OpenCC("s2tw")
    alone = [(c, cc.convert(c)) for c in keep if cc.convert(c) != c]
    in_phrases = [c for c in keep if cc.convert(c) == c]

    # Shortest phrase in which OpenCC changes the character, as an example.
    example = {}
    for key, values in table(fetch("STPhrases.txt")):
        target = values[0]
        if len(key) != len(target):
            continue
        for i, c in enumerate(key):
            if c in in_phrases and target[i] != c:
                if c not in example or len(key) < len(example[c][0]):
                    example[c] = (key, target)

    lines = [
        "# Characters that are valid in both Simplified and Traditional Chinese.",
        "# OpenCC would change them; transcribe.py keeps them as whisper wrote them.",
        "# One character per line; everything after it is a note.",
        f"# Generated by data/make_opencc_keep.py from OpenCC commit {COMMIT[:12]}.",
        "",
        f"# Changed by OpenCC even on their own ({len(alone)})",
    ]
    lines += [f"{c}\t# OpenCC: {c} → {t}" for c, t in alone]
    lines += ["", f"# Changed by OpenCC only inside some phrases ({len(in_phrases)})"]
    for c in in_phrases:
        if c in example:
            key, target = example[c]
            lines.append(f"{c}\t# e.g. {key} → {target}")
        else:
            lines.append(c)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(keep)} characters to {OUT}")


if __name__ == "__main__":
    main()
